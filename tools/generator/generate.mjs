// Generates src/generated/api.d.ts from spec/swagger.yaml.
//   node tools/generator/generate.mjs           write the file
//   node tools/generator/generate.mjs --check   fail if the committed file is stale
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const root = new URL('../../', import.meta.url)
const specUrl = new URL('spec/swagger.yaml', root)
const metaUrl = new URL('spec/spec.meta.json', root)
const outUrl = new URL('src/generated/api.d.ts', root)

const fail = (message) => {
  console.error(`generate: ${message}`)
  process.exit(1)
}

if (!existsSync(specUrl)) fail('spec/swagger.yaml is missing. Restore it from git or run `npm run spec:update`.')
if (!existsSync(metaUrl)) fail('spec/spec.meta.json is missing.')

const sha256 = createHash('sha256').update(readFileSync(specUrl)).digest('hex')
const meta = JSON.parse(readFileSync(metaUrl, 'utf8'))
if (meta.sha256 !== sha256) {
  fail(
    `spec/swagger.yaml (sha256 ${sha256}) does not match spec/spec.meta.json (${meta.sha256}). Run \`npm run spec:update\`.`,
  )
}

const generator = JSON.parse(
  readFileSync(new URL('node_modules/openapi-typescript/package.json', import.meta.url), 'utf8'),
)
const header = `/**
 * AUTO-GENERATED by tools/generator/generate.mjs from spec/swagger.yaml. Do not edit.
 *
 * Source: ${meta.source}
 * Documentation retrieved: ${meta.retrievedAt}
 * Spec sha256: ${sha256}
 * Generator: openapi-typescript@${generator.version}
 *
 * The specification is owned by Allegro; this file is derived from it.
 */

`

const output = header + astToString(await openapiTS(specUrl))

if (process.argv.includes('--check')) {
  const current = existsSync(outUrl) ? readFileSync(outUrl, 'utf8') : ''
  if (current !== output) fail('src/generated/api.d.ts is stale. Run `npm run generate` and commit the result.')
  console.log('generate: src/generated/api.d.ts is up to date')
} else {
  writeFileSync(outUrl, output)
  console.log(`generate: wrote src/generated/api.d.ts (${output.length} bytes)`)
}
